from pathlib import Path
import re

import openpyxl


TARGET_SHEETS = ("A8C4", "A8C5")
TARGET_HEADER = "customer_response_1"
THRESHOLD = 2
OUTPUT_FILE = "result_check_MaxHoldMaxValue_1stRead_RADAR.txt"
RESULTS_DIR_NAME = "MaxHold_Re-sim_RADAR_results"


def find_column_by_header(ws, target_header: str):
    """Return 1-based column index for the requested header on row 1."""
    target = target_header.strip().lower()
    for cell in ws[1]:
        if cell.value is None:
            continue
        if str(cell.value).strip().lower() == target:
            return cell.column
    return None


def parse_cell_as_int(value):
    """Parse numeric cells and simple '=HEX2DEC("XX")' formulas into integers."""
    if value is None:
        return None

    if isinstance(value, bool):
        return None

    if isinstance(value, int):
        return value

    if isinstance(value, float):
        return int(value)

    text = str(value).strip()
    if not text:
        return None

    # openpyxl reads formula text if workbook was not recalculated by Excel.
    # Support the formula generated by extractor scripts: =HEX2DEC("AB").
    m = re.fullmatch(r'=\s*HEX2DEC\("([0-9A-Fa-f]+)"\)\s*', text, flags=re.IGNORECASE)
    if m:
        return int(m.group(1), 16)

    try:
        return int(float(text))
    except ValueError:
        return None


def get_first_read_value(ws, skip_last_rows: int = 0):
    """Get MAX value from the first DID read column (customer_response_1)."""
    col = find_column_by_header(ws, TARGET_HEADER)
    if col is None:
        return None

    max_val = None
    end_row = ws.max_row - max(0, skip_last_rows)
    if end_row < 2:
        return None

    # Find MAX of all rows in customer_response_1 column
    for row in range(2, end_row + 1):
        parsed = parse_cell_as_int(ws.cell(row=row, column=col).value)
        if parsed is None:
            continue
        if max_val is None or parsed > max_val:
            max_val = parsed
    return max_val


def build_result_line(workbook_path: Path):
    wb = openpyxl.load_workbook(workbook_path, data_only=False)
    findings = []

    for sheet_name in TARGET_SHEETS:
        if sheet_name not in wb.sheetnames:
            continue

        ws = wb[sheet_name]
        skip_last_rows = 2 if sheet_name == "A8C5" else 0
        first_val = get_first_read_value(ws, skip_last_rows=skip_last_rows)
        if first_val is not None and first_val >= THRESHOLD:
            findings.append(f"{sheet_name} - max 1st read = {first_val}")

    wb.close()

    if not findings:
        return None

    return f"{workbook_path.stem}: " + " & ".join(findings)


def natural_sort_key(text: str) -> tuple:
    """Sort text by numeric chunks"""
    parts = re.split(r"(\d+)", text)
    return tuple(int(part) if part.isdigit() else part.lower() for part in parts)


def main():
    base_dir = Path(__file__).resolve().parent
    results_dir = base_dir / RESULTS_DIR_NAME
    workbook_paths = sorted(
        results_dir.glob("MaxHold_Re-sim_RADAR*.xlsx"),
        key=lambda p: natural_sort_key(p.stem),
    )

    results = []
    for workbook_path in workbook_paths:
        line = build_result_line(workbook_path)
        if line is not None:
            results.append(line)

    out_path = base_dir / OUTPUT_FILE
    with out_path.open("w", encoding="utf-8") as f:
        for line in results:
            f.write(f"{line}\n")

    print(f"Scanned {len(workbook_paths)} files")
    print(f"Found {len(results)} files with max 1st read >= {THRESHOLD}")
    print(f"Output: {out_path.name}")


if __name__ == "__main__":
    main()
